// experiments/glon-pratt/pratt_node_test.mjs -- GLON-PRATT v004 differential tests.
//
//   node pratt_node_test.mjs [GLON.WASM]                 run everything (WASM)
//   node pratt_node_test.mjs --write-fixtures OUT.glon   write the native fixture file
//
// The Glon parser (s-extra.glon, pratt.glon, math-grammar.glon) runs INSIDE the
// unchanged glon.wasm. Its output is compared with the v003 JavaScript
// reference (experiments/glon-latex/web/infix.js):
//   1. fixtures: the v003 translation and error tables, read from
//      infix_node_test.mjs (not copied), restricted to the arithmetic subset;
//   2. random differential testing: valid expressions and token soup;
//   3. the depth guard: shapes swept from small to far past the limit; every
//      run must succeed or raise the catchable 'too-deep error, and never halt;
//   4. measured practical limits;
//   5. Chris Ross-Gill's 17 figures: a resource-fit check (see the report).
// JavaScript here only hosts, supplies inputs and compares outputs. The
// parsing under test happens in Glon.
import fs from 'fs';
import { createRequire } from 'module';
import { fileURLToPath } from 'url';

const here = p => fileURLToPath(new URL(p, import.meta.url));
const ROOT = '../../';
const require = createRequire(import.meta.url);
const ref = require(here('../glon-latex/web/infix.js'));
const PARSER = ['s-extra.glon', 'pratt.glon', 'math-grammar.glon'].map(f => fs.readFileSync(here(f), 'utf8'));
const LIBS = [ROOT + 'jupyter/prelude.glon', ROOT + 'demo/shop/strings.glon'].map(f => fs.readFileSync(here(f), 'utf8'));

// ---- the v003 fixtures, read from the v003 test file -----------------------------------
const v003 = fs.readFileSync(here('../glon-latex/web/infix_node_test.mjs'), 'utf8');
const table = name => {
  const start = v003.indexOf('const ' + name + ' = [');
  const end = v003.indexOf('\n];', start);
  return new Function('return [' + v003.slice(v003.indexOf('[', start) + 1, end) + '];')();
};
const T = table('T'), E = table('E'), CHRIS = table('CHRIS');

// the arithmetic subset that math-grammar.glon implements
const SUBSET_WORDS = new Set(['l/+', 'l/-', 'l/*', 'l/frac', 'l/^', 'l/neg']);
const FEATURE_NAMES = /\b(sqrt|root|ln|sum|prod|int|lim|lim_left|lim_right|paren|bracket|brace|stack|pi|sigma|theta|inf|infinity)\b/;
const FEATURE_ERRORS = /two numbers|chained relations|needs its arguments|takes \d+ argument|is not allowed as argument|too long|'\['|brackets/;
// the reference result, as the Glon parser prints it
function reference(src) {
  const r = ref.translate(src);
  return r.error !== undefined ? 'error ' + r.pos + ': ' + r.error : r.glon;
}
function inSubset(src) {
  if (/[^\x00-\x7f]/.test(src) || /[,=\[\]~]/.test(src) || FEATURE_NAMES.test(src)) return false;
  const r = ref.translate(src);
  if (r.error !== undefined) return !FEATURE_ERRORS.test(r.error);
  return r.glon.split(' ').every(w => /^"/.test(w) || /^\d+$/.test(w) || SUBSET_WORDS.has(w));
}
const bytes = s => [...Buffer.from(s, 'utf8')].join(' ');
// `pre` overrides limits for calibration, e.g. 'p/max-depth: 90'
const program = (src, pre) => (pre ? pre + '\n' : '') + 'p/run m/grammar mk-string [ ' + bytes(src) + ' ]';

// ---- --write-fixtures: the same comparison, run by the NATIVE glon ----------------------
if (process.argv[2] === '--write-fixtures') {
  const cases = [...T.map(t => t[0]), ...E.map(e => e[0])].filter(inSubset);
  let out = ';; GENERATED by pratt_node_test.mjs --write-fixtures: the v003 fixtures in the\n' +
            ';; arithmetic subset, with the v003 reference (infix.js) result for each.\n' +
            'f/pass: 0\nf/fail: 0\n' +
            'f/result: func [src] [\n' +
            '    pt-e: judge [ p/translate m/grammar src ]\n' +
            '    either sin? pt-e [ s/+ "error " s/+ s/from-int block-at sin-arg pt-e 1 s/+ ": " block-at sin-arg pt-e 0 ] [ pt-e ]\n' +
            ']\n' +
            'f/check: func [src want] [\n' +
            '    pt-got: f/result src\n' +
            '    either s/= pt-got want [ f/pass: + f/pass 1 ] [\n' +
            '        f/fail: + f/fail 1  s/print s/+ "FAIL " src  s/print s/+ "  got:  " pt-got  s/print s/+ "  want: " want\n' +
            '    ]\n' +
            ']\n';
  for (const c of cases) out += 'do [ f/check mk-string [ ' + bytes(c) + ' ] mk-string [ ' + bytes(reference(c)) + ' ] ]\n';
  out += 'print f/pass\nprint f/fail\n' +
         'either = f/fail 0 [ s/print "glon-pratt native fixtures: all passed" ] [ raise create-sin \'test \'failed f/fail ]\n';
  fs.writeFileSync(process.argv[3], out);
  console.log('wrote ' + cases.length + ' fixture cases to ' + process.argv[3]);
  process.exit(0);
}

// ---- the runtime, driven as the browser hosts drive it -----------------------------------
const wasmPath = process.argv[2];
if (!wasmPath) { console.error('usage: node pratt_node_test.mjs GLON.WASM  (built from the current runtime; the committed demo/shop/glon.wasm is stale)'); process.exit(2); }
const mod = await WebAssembly.compile(fs.readFileSync(wasmPath));
async function glon(src, pre) {
  let ex; const out = [];
  const view = () => new Uint8Array(ex.memory.buffer);
  ex = (await WebAssembly.instantiate(mod, { env: {
    host_print: (p, n) => { for (const b of view().subarray(p, p + n)) out.push(b); },
    host_set_text() {}, host_set_html() {}, host_canvas_script() {} } })).exports;
  const put = s => { const b = new TextEncoder().encode(s); const p = ex.glon_alloc(b.length); view().set(b, p); return [p, b.length]; };
  if (ex.glon_init() !== 0) throw new Error('glon_init');
  for (const l of [...LIBS, ...PARSER]) if (ex.glon_load(...put(l)) !== 0) throw new Error('library failed to load');
  const before = out.length;
  if (ex.glon_run(...put(program(src, pre))) !== 0) return { line: null, result: 'program too long' };
  const result = new TextDecoder().decode(view().subarray(ex.glon_result_ptr(), ex.glon_result_ptr() + ex.glon_result_len()));
  const lines = new TextDecoder().decode(new Uint8Array(out.slice(before))).split('\n').filter(l => l && !l.startsWith('[dump]'));
  return { line: lines.length === 1 ? lines[0] : lines.join(' | '), result, halted: /halted/.test(result) };
}

let pass = 0, fail = 0;
const ok = (c, name, d) => { if (c) pass++; else { fail++; console.log('FAIL ' + name + (d !== undefined ? '\n     ' + d : '')); } };

// ---- 1. fixtures ------------------------------------------------------------------------------
const fixtureInputs = [...T.map(t => t[0]), ...E.map(e => e[0])];
const inside = fixtureInputs.filter(inSubset), outside = fixtureInputs.filter(s => !inSubset(s));
for (const src of inside) {
  const g = await glon(src), want = reference(src);
  ok(g.line === want && g.result === 'none', 'fixture ' + JSON.stringify(src), 'glon ' + g.line + ' (' + g.result + ')\n     ref  ' + want);
}
let outsideHalts = 0;
for (const src of outside) { const g = await glon(src); if (g.halted || g.result !== 'none') outsideHalts++; }
ok(outsideHalts === 0, 'fixtures outside the subset are reported as errors, never a halt', outsideHalts + ' halted');
console.log(`fixtures: ${inside.length} in the arithmetic subset (compared exactly), ${outside.length} outside it (need later grammar)`);

// ---- 2. random differential testing ------------------------------------------------------------
let seed = 20261106;
const rnd = n => { seed = (seed * 1103515245 + 12345) % 2147483648; return seed % n; };
const NAMES = ['a', 'b', 'c', 'x', 'y', 'dx', 'ab1', 'Z'];
const sp = () => [' ', '', '', '  '][rnd(4)];
function expr(d) {
  const k = d <= 0 ? rnd(3) : rnd(9);
  if (k === 0) return NAMES[rnd(NAMES.length)];
  if (k === 1) return String(rnd(1000));
  if (k === 2) return ['0', '007', '2.5', '.25', '1234567890123456'][rnd(5)];
  if (k === 3) return '(' + sp() + expr(d - 1) + sp() + ')';
  if (k === 4) return '-' + expr(d - 1);
  return expr(d - 1) + sp() + ['+', '-', '*', '/', '^'][k - 4 > 4 ? rnd(5) : k - 4] + sp() + expr(d - 1);
}
const SOUP = ['a', 'b', '1', '23', '(', ')', '+', '-', '*', '/', '^', ' ', '.', '_', '$', 'x_', '5.', '.5', 'q(', '"'];
let validN = 0, soupN = 0, skipped = 0, deep = 0;
for (let i = 0; i < 400; i++) {
  const src = i < 250 ? expr(2 + rnd(3)) : Array.from({ length: 1 + rnd(7) }, () => SOUP[rnd(SOUP.length)]).join('');
  if (!inSubset(src)) { skipped++; continue; }
  const g = await glon(src), want = reference(src);
  if (/too deeply nested/.test(g.line || '')) { deep++; continue; }
  i < 250 ? validN++ : soupN++;
  ok(g.line === want, 'random ' + JSON.stringify(src), 'glon ' + g.line + '\n     ref  ' + want);
}
console.log(`random: ${validN} expressions and ${soupN} token-soup inputs compared, ${skipped} outside the subset, ${deep} past the depth guard`);

// ---- 3 + 4. the guards and the practical limits ----------------------------------------------------
const LIMIT = name => Number(new RegExp('p/' + name + ': (\\d+)').exec(PARSER[1])[1]);
const MAXLEN = LIMIT('max-length'), MAXDEPTH = LIMIT('max-depth'), MAXCHAIN = LIMIT('max-chain');
const refused = line => /too deeply nested|too long for this parser/.test(line || '');
const SHAPES = {
  'a+a+...+a (terms)':        n => Array(n).fill('a').join('+'),
  'a*b+a*b+... (products)':   n => Array(n).fill('a*b').join('+'),
  'a^a^...^a (right assoc)':  n => Array(n).fill('a').join('^'),
  '((...a...)) (parentheses)': n => '('.repeat(n) + 'a' + ')'.repeat(n),
  'a*(a*(...)) (nesting)':    n => 'a*('.repeat(n) + 'a' + ')'.repeat(n),
  '---a (unary chain)':       n => '-'.repeat(n) + 'a',
  '-(-(...a)) (unary groups)': n => '-('.repeat(n) + 'a' + ')'.repeat(n),
  'x^-(...) (exponents)':     n => 'x^-('.repeat(n) + 'a' + ')'.repeat(n),
  'long names (14 bytes)':    n => Array(n).fill('abcdefghijklmn').join('+'),
  'long numerals (15 digits)': n => Array(n).fill('123456789012345').join('*'),
  'groups (abcdefghij+k)-...': n => Array(n).fill('(abcdefghij+k)').join('-'),
};
// 3a. return stack: with the heap limits lifted, the largest depth guard at which
// no NESTING shape halts. The shipped guard must leave room for callers.
const RS_SHAPES = ['((...a...)) (parentheses)', 'a*(a*(...)) (nesting)', '---a (unary chain)',
                   '-(-(...a)) (unary groups)', 'x^-(...) (exponents)', 'a^a^...^a (right assoc)'];
let lo = 10, hi = 200;
while (hi - lo > 1) {
  const mid = (lo + hi) >> 1; let h = 0;
  for (const k of RS_SHAPES) if ((await glon(SHAPES[k](110), `p/max-depth: ${mid}\np/max-chain: 999\np/max-length: 9999`)).halted) h++;
  if (h) hi = mid; else lo = mid;
}
console.log(`return stack: nesting halts beyond a depth guard of ${lo}; shipped p/max-depth ${MAXDEPTH}`);
ok(MAXDEPTH <= lo - 6, `p/max-depth ${MAXDEPTH} leaves at least 6 frames below ${lo} for callers`);
// 3b. heap stress: every chain length, operand lengths 1..40, + and *, up to the length cap
let stressHalts = 0, stressRuns = 0;
for (const k of [1, 2, 3, 5, 8, 10, 12, 14, 16, 20, 25, 30, 40]) {
  const name = 'abcdefghijklmnopqrstuvwxyzabcdefghijklmnopqrstuvwxyz'.slice(0, k);
  for (const op of ['+', '*', '-']) for (let n = 1; ; n++) {
    const src = Array(n).fill(name).join(op); if (src.length > MAXLEN + 20) break;
    stressRuns++;
    const g = await glon(src);
    if (g.halted) { stressHalts++; console.log('  heap halt: ' + k + '-byte operands, ' + n + ' terms, ' + src.length + ' bytes'); }
    else if (!refused(g.line)) ok(g.line === reference(src), 'stress ' + src.slice(0, 40), g.line);
  }
}
ok(stressHalts === 0, `heap stress: ${stressRuns} chains, none halts`, stressHalts + ' halts');
// 4. the limits, with the shipped guards: the largest n that parses in each shape
const limits = {};
let sweepHalts = 0;
for (const [name, mk] of Object.entries(SHAPES)) {
  let max = 0;
  for (let n = 1; n <= 200; n++) {
    const src = mk(n); if (src.length > MAXLEN + 40) break;
    const g = await glon(src);
    if (g.halted) { sweepHalts++; continue; }
    if (refused(g.line)) continue;
    if (g.line === reference(src)) max = n; else ok(false, 'limits ' + src.slice(0, 40), g.line);
  }
  limits[name] = max;
}
console.log(`limits with the shipped guards (p/max-depth ${MAXDEPTH}, p/max-chain ${MAXCHAIN}, p/max-length ${MAXLEN}):`);
for (const [name, max] of Object.entries(limits))
  console.log(`  ${name.padEnd(28)} ${String(max).padStart(3)}   (${SHAPES[name](max).length} bytes)`);
ok(sweepHalts === 0, 'no input in any shape halts the machine: the guards always report first', sweepHalts + ' halts');
// heavy random fuzz up to the length cap: never a halt; every accepted input matches
let fuzzHalts = 0, fuzzRefused = 0, fuzzOk = 0;
const longName = () => 'abcdefghijklmnopqrstuvwxyz'.slice(0, 1 + rnd(20));
function fexpr(d) {
  const k = d <= 0 ? rnd(3) : rnd(8);
  if (k === 0) return longName();
  if (k === 1) return String(rnd(100000));
  if (k === 2) return ['007', '2.5', '.25', '123456789012345'][rnd(4)];
  if (k === 3) return '(' + fexpr(d - 1) + ')';
  if (k === 4) return '-' + fexpr(d - 1);
  return fexpr(d - 1) + ['+', '-', '*', '/', '^'][rnd(5)] + fexpr(d - 1);
}
for (let i = 0; i < 500; i++) {
  const src = fexpr(4 + rnd(5)); if (src.length > MAXLEN || !inSubset(src)) continue;
  const g = await glon(src);
  if (g.halted) { fuzzHalts++; console.log('  fuzz halt: ' + src); }
  else if (refused(g.line)) fuzzRefused++;
  else { fuzzOk++; ok(g.line === reference(src), 'fuzz ' + JSON.stringify(src), 'glon ' + g.line + '\n     ref  ' + reference(src)); }
}
ok(fuzzHalts === 0, 'heavy random fuzz never halts', fuzzHalts + ' halts');
console.log(`heavy fuzz: ${fuzzOk} matched the reference, ${fuzzRefused} refused by a guard, ${fuzzHalts} halts`);
const guardMsg = (await glon(SHAPES['a+a+...+a (terms)'](limits['a+a+...+a (terms)'] + 1))).line;
ok(/^error \d+: expression too deeply nested for this parser$/.test(guardMsg), 'the chain guard reports a positioned, catchable error', guardMsg);
const nestMsg = (await glon(SHAPES['((...a...)) (parentheses)'](limits['((...a...)) (parentheses)'] + 1))).line;
ok(/^error \d+: expression too deeply nested for this parser$/.test(nestMsg), 'the depth guard reports a positioned, catchable error', nestMsg);
const big = 'a+'.repeat(100) + 'a';
ok((await glon(big)).line === 'error 0: expression too long for this parser (' + big.length + ' bytes)', 'input over the length cap is refused up front', (await glon(big)).line);
// input arrives as a byte block, so it is not bound by the 512-byte string-literal limit
const nameAtCap = 'a+' + 'b'.repeat(MAXLEN - 2);
ok((await glon(nameAtCap)).line === reference(nameAtCap), 'a name filling the length cap parses', (await glon(nameAtCap)).line);

// ---- 5. Chris Ross-Gill's figures: resource fit --------------------------------------------------
// The arithmetic grammar cannot express these figures (they need functions,
// relations, implicit multiplication, lists and symbols). To see whether
// they FIT the resource limits, each figure is rewritten into a conservative
// arithmetic skeleton that the real Glon parser can parse with the same nesting:
//   f(a, b, c) -> (a + b + c)   [ ] -> ( )   = ≈ , -> +   ÷ -> /   × · -> *
//   _ -> 0   implicit multiplication -> *   symbol names -> plain names
// Arguments joined with + cost extra fold frames that a real argument list
// would not, so the skeleton is at least as deep as the figure.
function figures(render) {   // split on top-level commas
  const out = []; let depth = 0, cur = '';
  for (const ch of render) {
    if (ch === '(' || ch === '[') depth++;
    if (ch === ')' || ch === ']') depth--;
    if (ch === ',' && depth === 0) { out.push(cur.trim()); cur = ''; } else cur += ch;
  }
  out.push(cur.trim()); return out;
}
function skeleton(src) {
  let s = src.replace(/[\[]/g, '(').replace(/[\]]/g, ')').replace(/[=≈,]/g, ' + ').replace(/÷/g, ' / ').replace(/[×·]/g, ' * ')
             .replace(/\b_\b/g, '0').replace(/\b(sqrt|root|ln|sum|prod|int|lim|lim_left|lim_right|paren|bracket|brace|stack)\s*\(/g, '(');
  // implicit multiplication: an operand end followed by an operand start
  const toks = s.match(/\d*\.\d+|\d+|[A-Za-z][A-Za-z0-9]*|\S/g);
  const endOp = t => /^[\w.]/.test(t) || t === ')', startOp = t => /^[\w.]/.test(t) || t === '(';
  return toks.map((t, i) => (i && endOp(toks[i - 1]) && startOp(t) ? '* ' : '') + t).join(' ');
}
const figs = CHRIS.flatMap(figures);
ok(figs.length === 17, 'Chris renders split into 17 figures', figs.length);
const fit = [];
for (let i = 0; i < figs.length; i++) {
  const sk = skeleton(figs[i]), g = await glon(sk);
  fit.push({ figure: i + 1, fits: !/error|halted/.test((g.line || '') + g.result), skeleton: sk, note: g.line });
}
console.log(`Chris figures: ${fit.filter(f => f.fits).length} of 17 fit the resource limits (conservative skeletons):`);
for (const f of fit) console.log(`  ${String(f.figure).padStart(2)} ${f.fits ? 'fits ' : 'DOES NOT FIT'}  ${f.skeleton.length} bytes  ${f.fits ? '' : f.note}`);
ok(fit.every(f => !/halted/.test(f.note || '')), 'no figure skeleton halts the machine');

console.log(`${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
