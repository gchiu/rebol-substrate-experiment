#!/usr/bin/env python3
"""Generate four original 64x64 Glon AvP textures as a C header.
Deterministic; no external image assets or copyrighted samples."""
import sys

W = H = 64
def h(x, y, s=0):
    n = (x * 374761393 + y * 668265263 + s * 69069 + 0x9e3779b9) & 0xffffffff
    n = (n ^ (n >> 13)) * 1274126177 & 0xffffffff
    return (n ^ (n >> 16)) & 0xff
def clamp(v): return 0 if v < 0 else 255 if v > 255 else v
def rgb(r, g, b, a=255): return (a << 24) | (clamp(r) << 16) | (clamp(g) << 8) | clamp(b)
def wear(x, y, seed, amount=8): return h(x, y, seed) % (amount * 2 + 1) - amount

def wall(x, y):
    n = wear(x, y, 1, 7)
    r, g, b = 72 + n, 80 + n, 88 + n
    # two-panel industrial tile
    if x % 32 < 2 or y % 32 < 2: r, g, b = 30, 36, 42
    if x % 32 in (3, 4) or y % 32 in (3, 4): r, g, b = 105, 112, 116
    # raised bolt heads
    for bx, by in ((6, 6), (26, 6), (38, 6), (58, 6),
                   (6, 26), (26, 26), (38, 26), (58, 26),
                   (6, 38), (26, 38), (38, 38), (58, 38)):
        dx, dy = x - bx, y - by
        if dx * dx + dy * dy <= 2:
            r, g, b = 128, 134, 136
    # recessed vent and slits
    if 10 <= x <= 54 and 45 <= y <= 53:
        r, g, b = 54, 60, 66
        if y in (46, 48, 50, 52) and 13 <= x <= 51: r, g, b = 22, 27, 32
        if y in (45, 53) and x in (10, 54): r, g, b = 108, 114, 118
    # subtle wear streaks
    if h(x, y, 9) % 31 == 0: r, g, b = r - 15, g - 13, b - 11
    return rgb(r, g, b)

def floor(x, y):
    n = wear(x, y, 2, 5)
    r, g, b = 34 + n, 39 + n, 43 + n
    # heavy grating bars
    if x % 16 < 4 or y % 16 < 4:
        r, g, b = 74 + n, 82 + n, 87 + n
        if x % 16 == 0 or y % 16 == 0: r, g, b = 105, 112, 112
    # dark grating voids
    if 7 <= x % 16 <= 12 and 7 <= y % 16 <= 12:
        r, g, b = 16, 20, 24
    # cross braces and wear
    if (x + y) % 32 == 0: r, g, b = 60, 66, 69
    if h(x, y, 7) % 47 == 0: r, g, b = r + 22, g + 20, b + 16
    return rgb(r, g, b)

def ceiling(x, y):
    n = wear(x, y, 3, 5)
    r, g, b = 51 + n, 58 + n, 64 + n
    if x % 32 < 2 or y % 32 < 2: r, g, b = 25, 31, 37
    if x % 32 in (3, 4) or y % 32 in (3, 4): r, g, b = 88, 96, 101
    # recessed warm light in each panel
    if 8 <= x % 32 <= 24 and 25 <= y % 32 <= 32:
        r, g, b = 190, 196, 166
        if y % 32 in (25, 32): r, g, b = 112, 118, 105
    # ventilation slots
    if 8 <= x % 32 <= 24 and 8 <= y % 32 <= 17:
        r, g, b = 35, 41, 47
        if y % 3 == 0: r, g, b = 19, 24, 29
    return rgb(r, g, b)

def door(x, y):
    n = wear(x, y, 4, 4)
    r, g, b = 154 + n, 114 + n, 54 + n
    # heavy outer frame
    if x < 4 or x > 59 or y < 4 or y > 59: r, g, b = 54, 45, 32
    if x in (4, 59) or y in (4, 59): r, g, b = 102, 77, 40
    # mechanical beams and central seam
    if y in (13, 14, 49, 50): r, g, b = 92, 69, 37
    if x in (31, 32): r, g, b = 75, 56, 33
    # bolts and warning plates
    for bx, by in ((9, 9), (54, 9), (9, 54), (54, 54), (9, 39), (54, 39)):
        dx, dy = x - bx, y - by
        if dx * dx + dy * dy <= 2: r, g, b = 218, 188, 105
    if 12 <= x <= 23 and 27 <= y <= 36: r, g, b = 194, 151, 67
    if 41 <= x <= 52 and 27 <= y <= 36: r, g, b = 194, 151, 67
    return rgb(r, g, b)

def emit(name, fn, out):
    vals = [fn(x, y) for y in range(H) for x in range(W)]
    out.write(f"static const uint32_t tex_{name}[{W*H}] = {{\n")
    for i in range(0, len(vals), 8):
        out.write("  " + ", ".join(f"0x{v:08x}u" for v in vals[i:i+8]) + ",\n")
    out.write("};\n\n")

def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen_textures.py OUT.h")
    with open(sys.argv[1], "w") as f:
        f.write("/* Generated by tools/gen_textures.py. Original procedural textures. */\n")
        f.write("#ifndef GLON_AVP_TEXTURES_H\n#define GLON_AVP_TEXTURES_H\n#include <stdint.h>\n\n")
        emit("wall", wall, f); emit("floor", floor, f)
        emit("ceiling", ceiling, f); emit("door", door, f)
        f.write("#endif\n")

if __name__ == "__main__":
    main()
