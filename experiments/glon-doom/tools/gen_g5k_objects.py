#!/usr/bin/env python3
"""Original 64x96 transparent industrial props for G5k."""
from PIL import Image,ImageDraw
import pathlib
ROOT=pathlib.Path(__file__).resolve().parent.parent; OUT=ROOT/'sprites'/'objects'; OUT.mkdir(parents=True,exist_ok=True); HEADER=ROOT/'object_sprites.h'
S=4; W,H=64,96
def p(v): return tuple(int(x*S) for x in v)
def poly(d,pts,fill,outline=(8,10,10,255),w=2): d.polygon([(int(x*S),int(y*S)) for x,y in pts],fill=fill,outline=outline,width=w*S)
def ell(d,b,fill,outline=(8,10,10,255),w=2): d.ellipse([int(v*S) for v in b],fill=fill,outline=outline,width=w*S)
def line(d,pts,c,w=2): d.line([(int(x*S),int(y*S)) for x,y in pts],fill=c,width=w*S)
def base(name,draw):
 im=Image.new('RGBA',(W*S,H*S),(0,0,0,0)); d=ImageDraw.Draw(im); draw(d); im=im.resize((W,H),Image.Resampling.LANCZOS); im.save(OUT/f'{name}.png'); return list(im.getdata())
def drum(d):
 ell(d,(14,12,50,96), (126,38,28,255)); ell(d,(18,14,46,92),(172,53,38,255));
 for y in (22,74): line(d,[(15,y),(49,y)],(30,22,18,255),3); line(d,[(18,y+3),(46,y+3)],(205,94,54,255),1)
 line(d,[(23,20),(23,84)],(70,20,16,255),2)
def crate(d):
 poly(d,[(9,18),(55,18),(55,92),(9,92)],(76,92,100,255)); poly(d,[(13,22),(51,22),(51,88),(13,88)],(103,120,126,255));
 for x in (13,30,47): line(d,[(x,22),(x,88)],(42,52,58,255),3)
 line(d,[(13,50),(51,50)],(42,52,58,255),3)
 for x in (18,38): ell(d,(x,12,x+12,24),(157,164,160,255),w=1)
def cabinet(d):
 poly(d,[(10,12),(54,12),(54,94),(10,94)],(48,62,68,255)); poly(d,[(14,16),(50,16),(50,90),(14,90)],(76,94,99,255));
 for y in (28,46,64): line(d,[(17,y),(47,y)],(32,42,48,255),3)
 ell(d,(37,22,41,26),(214,190,86,255),w=1); ell(d,(37,40,41,44),(103,196,122,255),w=1)
 for x in (21,43): line(d,[(x,70),(x,86)],(26,33,37,255),2)
def container(d):
 poly(d,[(5,54),(59,54),(59,91),(5,91)],(72,84,91,255)); poly(d,[(9,58),(55,58),(55,87),(9,87)],(96,112,116,255));
 for x in (17,29,41,53): line(d,[(x,58),(x,87)],(40,50,55,255),2)
 line(d,[(9,58),(55,58)],(158,164,158,255),2); line(d,[(9,87),(55,87)],(28,35,40,255),2)
def main():
 frames={'drum':base('drum',drum),'crate':base('crate',crate),'cabinet':base('cabinet',cabinet),'container':base('container',container)}
 with open(HEADER,'w') as f:
  f.write('/* Original G5k industrial props, generated by tools/gen_g5k_objects.py. */\n')
  f.write('#ifndef GLON_AVP_OBJECT_SPRITES_H\n#define GLON_AVP_OBJECT_SPRITES_H\n#include <stdint.h>\n#define OBJ_W 64\n#define OBJ_H 96\n\n')
  for n,v in frames.items():
   f.write(f'static const uint32_t obj_{n}[OBJ_W*OBJ_H] = {{\n')
   for i in range(0,len(v),8): f.write('  '+', '.join('0x%08xu'%((a<<24)|(r<<16)|(g<<8)|b) for r,g,b,a in v[i:i+8])+',\n')
   f.write('};\n\n')
  f.write('#endif\n')
 print('wrote',len(frames),'props')
if __name__=='__main__': main()
