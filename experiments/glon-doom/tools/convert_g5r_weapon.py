#!/usr/bin/env python3
"""Build a transparent first-person pulse-rifle/hands sprite from the G5r sheet.

The source is a full corridor illustration.  The silhouette below is hand traced
to keep the weapon and both visible hands while discarding the baked corridor.
The illustrated green 60 is blanked; the runtime draws Glon's ammunition value.
"""
from PIL import Image, ImageDraw
import os

SRC = 'assets/weapons/reference/pulse-rifle-reference.png'
OUT = 'assets/weapons/pulse-rifle-hands.png'
HEADER = 'weapon_sprites.h'
CROP = (580, 455, 1500, 941)   # x0,y0,x1,y1 in the reference
OUT_W, OUT_H = 768, 406

# Outer silhouette in reference coordinates, traced clockwise from the sleeve.
OUTLINE = [
    (585, 941), (585, 905), (598, 885), (618, 865), (640, 850),
    (660, 835), (680, 814), (695, 788), (706, 758), (716, 728),
    (726, 696), (736, 668), (750, 645), (765, 632), (778, 625),
    (790, 616), (800, 604), (805, 590), (800, 575), (792, 562),
    (802, 552), (820, 545), (828, 520), (834, 490), (842, 480),
    (851, 480), (858, 495), (865, 510), (885, 514), (910, 516),
    (935, 520), (960, 522), (985, 526), (1010, 522), (1035, 526),
    (1055, 536), (1075, 545), (1095, 552), (1115, 562), (1135, 578),
    (1148, 598), (1160, 620), (1180, 650), (1200, 680), (1220, 708),
    (1248, 742), (1280, 778), (1310, 810), (1340, 842), (1370, 870),
    (1400, 895), (1430, 918), (1460, 934), (1490, 941)
]
# Corridor visible through the carry-handle opening must not be baked in.
HOLES = [
    [(938, 571), (1028, 566), (1040, 584), (1040, 614), (1024, 632),
     (985, 637), (948, 620), (932, 596)]
]
# Screen interior around the baked 60. Coordinates in reference space.
SCREEN = (1112, 687, 1202, 756)
# Visible barrel exit in the reference crop; maps to the centre of the small
# muzzle cylinder at the front-left of the weapon silhouette.
MUZZLE = (805, 570)


def main():
    im = Image.open(SRC).convert('RGBA')
    x0, y0, x1, y1 = CROP
    rgba = im.crop(CROP)
    w, h = rgba.size

    # Supersample the traced silhouette for clean transparent edges.
    ss = 4
    mask = Image.new('L', (w*ss, h*ss), 0)
    d = ImageDraw.Draw(mask)
    pts = [((x-x0)*ss, (y-y0)*ss) for x, y in OUTLINE]
    d.polygon(pts, fill=255)
    for hole in HOLES:
        d.polygon([((x-x0)*ss, (y-y0)*ss) for x, y in hole], fill=0)
    mask = mask.resize((w, h), Image.LANCZOS)

    # Erode the outermost edge slightly to avoid corridor colour fringes.
    from PIL import ImageFilter
    mask = mask.filter(ImageFilter.MinFilter(3))
    rgba.putalpha(Image.composite(rgba.getchannel('A'), Image.new('L', (w, h), 0), mask))

    # Remove the baked 60 and leave a dark live-display surface.
    sx0, sy0, sx1, sy1 = SCREEN
    screen = (sx0-x0, sy0-y0, sx1-x0, sy1-y0)
    d = ImageDraw.Draw(rgba)
    d.rectangle(screen, fill=(3, 9, 2, 255))
    # subtle inner bezel, not digits
    d.rectangle((screen[0]+2, screen[1]+2, screen[2]-2, screen[1]+5), fill=(10, 25, 5, 255))

    rgba = rgba.resize((OUT_W, OUT_H), Image.LANCZOS)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    rgba.save(OUT)

    # Runtime header, top-down rows matching gl_upload's source convention.
    px = rgba.load()
    os.makedirs(os.path.dirname(HEADER) or '.', exist_ok=True)
    with open(HEADER, 'w') as f:
        f.write('/* Generated by tools/convert_g5r_weapon.py from the supplied G5r pulse-rifle reference. */\n')
        f.write('#ifndef GLON_AVP_WEAPON_SPRITES_H\n#define GLON_AVP_WEAPON_SPRITES_H\n')
        f.write('#include <stdint.h>\n')
        f.write(f'#define WEAPON_W {OUT_W}\n#define WEAPON_H {OUT_H}\n')
        sw, sh = rgba.size
        def sxy(x, y):
            return (round((x - CROP[0]) * sw / (CROP[2] - CROP[0])),
                    round((y - CROP[1]) * sh / (CROP[3] - CROP[1])))
        s0 = sxy(SCREEN[0], SCREEN[1]); s1 = sxy(SCREEN[2], SCREEN[3])
        m = sxy(MUZZLE[0], MUZZLE[1])
        f.write(f'#define WEAPON_SCREEN_X0 {s0[0]}\n#define WEAPON_SCREEN_Y0 {s0[1]}\n')
        f.write(f'#define WEAPON_SCREEN_X1 {s1[0]}\n#define WEAPON_SCREEN_Y1 {s1[1]}\n')
        f.write(f'#define WEAPON_MUZZLE_X {m[0]}\n#define WEAPON_MUZZLE_Y {m[1]}\n\n')
        f.write('static const uint32_t weapon_pulse[WEAPON_W*WEAPON_H] = {\n')
        for y in range(OUT_H):
            f.write('  ')
            for x in range(OUT_W):
                r, g, b, a = px[x, y]
                f.write(f'0x{a:02x}{r:02x}{g:02x}{b:02x}u,')
            f.write('\n')
        f.write('};\n\n#endif\n')
    print(f'wrote {OUT} and {HEADER}: {OUT_W}x{OUT_H}, blank screen={screen}')

if __name__ == '__main__':
    main()
