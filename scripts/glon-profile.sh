#!/bin/sh
# scripts/glon-profile.sh - the single generator for Glon memory profiles
# (GLON-CORE-C2).
#
#   sh scripts/glon-profile.sh PROFILE-FILE OUTDIR
#
# PROFILE-FILE (profiles/<name>.profile) declares every capacity of a profile
# together, as KEY=VALUE lines (# starts a comment; nothing is evaluated).
# OUTDIR receives:
#   glon_profile.h  every layout/capacity constant, force-included (-include)
#                   into each translation unit of a profiled build;
#   s1_profile.h    frozen s1.h with only MEM_CELLS replaced;
#   s1_profile.c    frozen s1.c with only its header name and (if the profile
#                   moves the code/data-stack boundary) DS_INIT replaced;
#   layout.txt      the region map, for people.
# The frozen files are only read.  The constrained profile is the 64K reference
# and is built from the frozen sources directly; generating it is only used to
# verify that its declared values equal the built-in defaults.
#
# Fixed by the frozen map (not profile parameters): code starts at 256; the
# main return stack top is 24576; the fixed runtime-state cells occupy
# [24576, 32768); the managed heap starts at 32768.  A profile with TASKS>=1
# has a task arena (TASKS x TASK_CELLS) and the 536-cell task table; a
# profile with TASKS=0 has neither (no M1 tasks can exist), so no region is
# shared by the loader and task state.  The runtime checks the generated layout again at compile time
# (r0_s1_layout.h), so a hand-made header cannot bypass the rules either.
set -eu

die() { echo "glon-profile: $*" >&2; exit 1; }

[ $# -eq 2 ] || die "usage: glon-profile.sh PROFILE-FILE OUTDIR"
pf=$1
out=$2
[ -f "$pf" ] || die "no profile file '$pf'"
here=$(cd "$(dirname "$0")/.." && pwd)

# ---- read KEY=VALUE (values: integers, 'auto', words) ----------------------
keys="NAME STATUS MEM_CELLS CODE_CAP MANAGED_CELLS WORKLIST WORKLIST_CELLS LOADER_CELLS TAIL_CELLS TASKS TASK_CELLS TASK_DS_OFF TASK_RS_OFF GLOBAL_CAP SYM_CAP"
for k in $keys; do eval "P_$k="; done
lineno=0
while IFS= read -r line || [ -n "$line" ]; do
    lineno=$((lineno + 1))
    line=${line%%#*}
    line=$(printf '%s' "$line" | tr -d ' \t\r')
    [ -n "$line" ] || continue
    case "$line" in
        *=*) k=${line%%=*}; v=${line#*=} ;;
        *) die "$pf:$lineno: expected KEY=VALUE" ;;
    esac
    case " $keys " in *" $k "*) ;; *) die "$pf:$lineno: unknown key '$k'" ;; esac
    case "$v" in
        ''|*[!A-Za-z0-9_.-]*) die "$pf:$lineno: bad value '$v' for $k" ;;
    esac
    eval "cur=\${P_$k}"
    [ -z "$cur" ] || die "$pf:$lineno: $k declared twice"
    eval "P_$k=\$v"
done < "$pf"
for k in $keys; do
    eval "v=\${P_$k}"
    [ -n "$v" ] || die "$pf: $k is not declared (every capacity must be declared together)"
done

num() {  # num KEY VALUE: VALUE must be a non-negative integer
    case "$2" in ''|*[!0-9]*) die "$pf: $1 must be a non-negative integer, not '$2'" ;; esac
}
for k in CODE_CAP MANAGED_CELLS WORKLIST_CELLS TAIL_CELLS TASKS TASK_CELLS TASK_DS_OFF TASK_RS_OFF GLOBAL_CAP SYM_CAP; do
    eval "num $k \${P_$k}"
done
case "$P_WORKLIST" in fixed|after-heap) ;; *) die "$pf: WORKLIST must be 'fixed' or 'after-heap'" ;; esac
case "$P_STATUS" in reference|verified|provisional) ;; *) die "$pf: STATUS must be reference, verified or provisional" ;; esac

# ---- layout ----------------------------------------------------------------
HEAP_BASE=32768                    # frozen s1.c HEAP_BASE == GC_HEAP_BASE
if [ "$P_TASKS" -gt 0 ]; then
    TABLE_CELLS=536                # task records + wrapper blocks (m1_layout.h)
else
    TABLE_CELLS=0                  # no tasks: no task table either
fi
managed_end=$((HEAP_BASE + P_MANAGED_CELLS))
if [ "$P_WORKLIST" = fixed ]; then
    worklist=25057                 # inside the fixed runtime-state region
    load_base=$managed_end
else
    worklist=$managed_end
    load_base=$((managed_end + P_WORKLIST_CELLS))
fi
arena_cells=$((P_TASKS * P_TASK_CELLS))
if [ "$P_LOADER_CELLS" = auto ]; then
    num MEM_CELLS "$P_MEM_CELLS"
    loader=$((P_MEM_CELLS - load_base - arena_cells - TABLE_CELLS - P_TAIL_CELLS))
    [ "$loader" -gt 0 ] || die "$pf: MEM_CELLS $P_MEM_CELLS leaves no loader heap"
else
    num LOADER_CELLS "$P_LOADER_CELLS"
    loader=$P_LOADER_CELLS
fi
arena_base=$((load_base + loader))
task_table=$((arena_base + arena_cells))
end=$((task_table + TABLE_CELLS + P_TAIL_CELLS))
if [ "$P_MEM_CELLS" = auto ]; then
    mem=$end
else
    num MEM_CELLS "$P_MEM_CELLS"
    mem=$P_MEM_CELLS
    [ "$end" -le "$mem" ] || die "$pf: regions end at $end, beyond MEM_CELLS $mem"
fi
heap_limit=$arena_base             # the loader never shares cells with task state

mkdir -p "$out"

# ---- glon_profile.h --------------------------------------------------------
tmp="$out/glon_profile.h.tmp"
{
    echo "/* GENERATED by scripts/glon-profile.sh from $(basename "$pf") -- do not edit."
    echo " * Profile '$P_NAME' ($P_STATUS).  Force-included into every translation"
    echo " * unit of a profiled build; checked again by r0_s1_layout.h. */"
    echo "#ifndef GLON_PROFILE_H"
    echo "#define GLON_PROFILE_H"
    echo "#define GLON_PROFILE_NAME \"$P_NAME\""
    echo "#define GLON_PROFILE_MEM_CELLS ${mem}L"
    echo "#define R0S1_DS_INIT ${P_CODE_CAP}L"
    echo "#define R0S1_HEAP_BASE ${managed_end}L"
    echo "#define R0S1_LOAD_BASE ${load_base}L"
    echo "#define R0S1_HEAP_LIMIT ${heap_limit}L"
    if [ "$P_WORKLIST" = after-heap ]; then
        echo "#define GC_WORKLIST ${worklist}L"
    fi
    echo "#define GC_WORKLIST_CAP ${P_WORKLIST_CELLS}L"
    # M1_* addresses are stringified into RAW assembly by the M1 test/host
    # library, so they must stay plain integers (a trailing L becomes a token).
    echo "#define M1_ARENA_BASE ${arena_base}"
    echo "#define M1_TASK_TABLE ${task_table}"
    echo "#define M1_MAX_TASKS ${P_TASKS}"
    echo "#define M1_TASK_CELLS ${P_TASK_CELLS}"
    echo "#define M1_DS_OFF ${P_TASK_DS_OFF}"
    echo "#define M1_RS_OFF ${P_TASK_RS_OFF}"
    echo "#define R0S1_GLOBAL_CAP ${P_GLOBAL_CAP}L"
    echo "#define R0S1_SYM_CAP ${P_SYM_CAP}L"
    echo "#endif"
} > "$tmp"
mv "$tmp" "$out/glon_profile.h"

# ---- generated S1 copy (frozen files are only read) -------------------------
sed "s/^#define MEM_CELLS 65536\$/#define MEM_CELLS $mem/" "$here/s1.h" > "$out/s1_profile.h.tmp"
grep -q "^#define MEM_CELLS $mem\$" "$out/s1_profile.h.tmp" || die "s1.h: MEM_CELLS line not found"
mv "$out/s1_profile.h.tmp" "$out/s1_profile.h"
sed -e 's/^#include "s1.h"$/#include "s1_profile.h"/' \
    -e "s/^#define DS_INIT  *16384\$/#define DS_INIT    $P_CODE_CAP/" "$here/s1.c" > "$out/s1_profile.c.tmp"
grep -q '^#include "s1_profile.h"$' "$out/s1_profile.c.tmp" || die "s1.c: header include not found"
grep -q "^#define DS_INIT  *$P_CODE_CAP\$" "$out/s1_profile.c.tmp" || die "s1.c: DS_INIT line not found"
grep -q '^#define RS_INIT  *24576$' "$out/s1_profile.c.tmp" || die "s1.c: RS_INIT is not the frozen 24576"
grep -q '^#define HEAP_BASE  *32768$' "$out/s1_profile.c.tmp" || die "s1.c: HEAP_BASE is not the frozen 32768"
mv "$out/s1_profile.c.tmp" "$out/s1_profile.c"

# ---- layout.txt ------------------------------------------------------------
{
    echo "profile $P_NAME ($P_STATUS) -- $mem cells"
    printf '  %-26s %10s %10s %10s\n' region start end cells
    row() { printf '  %-26s %10s %10s %10s\n' "$1" "$2" "$3" $(($3 - $2)); }
    row "registers/scratch" 0 256
    row "code (limit DS-256)" 256 $((P_CODE_CAP - 256))
    row "data-stack reserve" $((P_CODE_CAP - 256)) "$P_CODE_CAP"
    row "main return stack" "$P_CODE_CAP" 24576
    row "fixed runtime state" 24576 32768
    if [ "$P_WORKLIST" = fixed ]; then
        echo "    (GC worklist $P_WORKLIST_CELLS entries at 25057, inside the fixed state)"
    fi
    row "managed heap" "$HEAP_BASE" "$managed_end"
    if [ "$P_WORKLIST" = after-heap ]; then row "GC worklist" "$worklist" "$load_base"; fi
    row "loader heap" "$load_base" "$heap_limit"
    if [ "$P_TASKS" -gt 0 ]; then
        row "M1 task arena ($P_TASKS x $P_TASK_CELLS)" "$arena_base" "$task_table"
        row "task table" "$task_table" $((task_table + TABLE_CELLS))
    else
        echo "    (no M1 tasks: no task arena and no task table)"
    fi
    if [ "$P_TAIL_CELLS" -gt 0 ]; then row "tail" $((task_table + TABLE_CELLS)) "$end"; fi
    if [ "$end" -lt "$mem" ]; then row "unused" "$end" "$mem"; fi
    echo "  globals $P_GLOBAL_CAP, symbols $P_SYM_CAP, hash radix $P_GLOBAL_CAP"
} > "$out/layout.txt"
